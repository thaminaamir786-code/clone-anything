function generateReconstruction(facts, opts) {
  const options = opts || {};
  const isDemo = Boolean(options.demo);
  let files;

  if (isDemo) {
    files = demoSourceFiles();
  } else {
    files = {
      'package.json': JSON.stringify({
        name: 'reconstruction-' + slug(facts.name || 'app'),
        version: '0.1.0',
        private: true,
        description: 'Original reconstruction generated from authorized analysis',
        scripts: { start: 'node src/index.js', test: 'node --test tests/*.test.js' },
        license: 'MIT'
      }, null, 2) + '\n',
      'src/index.js': indexSource(facts),
      'src/analysis-report.json': JSON.stringify(facts, null, 2) + '\n',
      'README.md': genericReadme(facts, options)
    };
  }

  files['tests/smoke.test.js'] = testSource();
  files['LICENSE'] = LICENSE_TEXT;
  files['THIRD_PARTY_NOTICES.md'] = NOTICE_TEXT;
  return files;
}

